  function overallOf(p) {
    return P(function () { return SS.Progress.overallStats(p); }, null) || { completed: 0, total: 0, stars: 0, maxStars: 0, xp: 0, maxXp: 0, percent: 0 };
  }

  function starText(n) {
    n = Math.max(0, Math.min(3, n || 0));
    return "★★★".slice(0, n) + "☆☆☆".slice(0, 3 - n);
  }

