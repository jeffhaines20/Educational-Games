  function downloadReport(p) {
    try {
      var doc = document.implementation.createHTMLDocument("Progress Report");
      doc.title = "Progress Report – " + (p.wizardName || "Apprentice") + " – Syntax & Sorcery";
      var meta = doc.createElement("meta");
      meta.setAttribute("charset", "utf-8");
      doc.head.insertBefore(meta, doc.head.firstChild);
      var style = doc.createElement("style");
      style.textContent = REPORT_CSS;
      doc.head.appendChild(style);
      doc.body.appendChild(doc.importNode(reportNode(p), true));
      var html = "<!DOCTYPE html>\n" + doc.documentElement.outerHTML;
      var safeName = String(p.wizardName || "wizard").replace(/[^\w\- ]+/g, "").trim().replace(/\s+/g, "-") || "wizard";
      return u.downloadText("progress-report-" + safeName + ".html", html, "text/html;charset=utf-8");
    } catch (err) {
      return false;
    }
  }

  function printReport(p) {
    var ok = UI.dialogs.printNode(reportNode(p), "report");
    if (!ok) UI.dialogs.toast("Printing is blocked here. Use “Download report” instead.", { icon: "⚠️", kind: "warn" });
  }

