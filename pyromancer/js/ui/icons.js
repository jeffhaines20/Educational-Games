  function data() { return SS.ICON_DATA || {}; }

  function has(name) {
    return typeof name === "string" && Object.prototype.hasOwnProperty.call(data(), name);
  }

  /** An inline <svg> for an icon name, or null if the icon isn't available. */
  function svg(name, opts) {
    opts = opts || {};
    if (!has(name) || typeof document === "undefined") return null;
    var el = document.createElementNS(NS, "svg");
    el.setAttribute("viewBox", "0 0 512 512");
    el.setAttribute("class", "gi gi-" + name + (opts.className ? " " + opts.className : ""));
    el.setAttribute("focusable", "false");
    if (opts.label) {
      el.setAttribute("role", "img");
      el.setAttribute("aria-label", String(opts.label));
    } else {
      el.setAttribute("aria-hidden", "true");
    }
    var path = document.createElementNS(NS, "path");
    path.setAttribute("d", data()[name]);
    path.setAttribute("fill", "currentColor");
    el.appendChild(path);
    return el;
  }

  /** Icon name for a content value: an emoji, "icon:<name>", or a bare icon name. */
  function nameFor(value) {
    if (value === null || value === undefined) return null;
    var text = String(value).trim();
    if (!text) return null;
    if (text.indexOf("icon:") === 0) {
      text = text.slice(5);
      return has(text) ? text : null;
    }
    if (has(text)) return text;
    var name = normalised[text] || normalised[text.replace(/️/g, "")];
    return name && has(name) ? name : null;
  }

  /** An <svg> for a content value, falling back to a <span> showing the original text. */
  function fromContent(value, opts) {
    var name = nameFor(value);
    if (name) return svg(name, opts);
    var span = document.createElement("span");
    span.className = "emoji-fallback" + (opts && opts.className ? " " + opts.className : "");
    span.textContent = value === null || value === undefined ? "" : String(value);
    if (opts && opts.label) {
      span.setAttribute("role", "img");
      span.setAttribute("aria-label", String(opts.label));
    } else {
      span.setAttribute("aria-hidden", "true");
    }
    return span;
  }

  /** Every icon name this file refers to (used by tools/build_icons.js). */
  function allNames() {
    var names = {};
    [EMOJI, CHAPTERS, CHARACTERS, UI].forEach(function (table) {
      Object.keys(table).forEach(function (key) { names[table[key]] = true; });
    });
    return Object.keys(names).sort();
  }

