#!/usr/bin/env node
/*
 * Builds js/ui/icon-data.js: the path data for every icon named in js/ui/icons.js,
 * taken from game-icons.net (via the @iconify-json/game-icons npm package).
 *
 *   node tools/build_icons.js
 *
 * Add an icon name to a table in js/ui/icons.js (browse https://game-icons.net),
 * re-run this tool, and commit both files. The package is cached in tools/.cache.
 */
"use strict";
const fs = require("fs");
const os = require("os");
const path = require("path");
const vm = require("vm");
const { execFileSync } = require("child_process");

const PACKAGE = "@iconify-json/game-icons@1.2.4";
const root = path.resolve(__dirname, "..");
const cacheDir = path.join(__dirname, ".cache", "game-icons");
const cached = path.join(cacheDir, "icons.json");

function ensurePackage() {
  if (fs.existsSync(cached)) return;
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "game-icons-"));
  console.log("Downloading " + PACKAGE + " …");
  const tgz = execFileSync("npm", ["pack", PACKAGE, "--silent"], { cwd: tmp, encoding: "utf8" }).trim().split("\n").pop();
  execFileSync("tar", ["xzf", tgz], { cwd: tmp });
  fs.mkdirSync(cacheDir, { recursive: true });
  fs.copyFileSync(path.join(tmp, "package", "icons.json"), cached);
  fs.rmSync(tmp, { recursive: true, force: true });
}

function namesUsed() {
  const sandbox = { console };
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(path.join(root, "js", "ui", "icons.js"), "utf8"), sandbox, { filename: "icons.js" });
  return sandbox.SS.Icons.allNames();
}

ensurePackage();
const set = JSON.parse(fs.readFileSync(cached, "utf8"));
const names = namesUsed();
const out = {};
const problems = [];
for (const name of names) {
  const icon = set.icons[name];
  if (!icon) { problems.push(name + ": no such icon"); continue; }
  const match = /^<path fill="currentColor" d="([^"]+)"\/>$/.exec(icon.body);
  if (!match) { problems.push(name + ": not a single path"); continue; }
  out[name] = match[1];
}
if (problems.length) {
  console.error("Cannot build icon data:\n  " + problems.join("\n  "));
  process.exit(1);
}

const lines = [
  "/*",
  " * Pyromancer — icon path data (SS.ICON_DATA). GENERATED by tools/build_icons.js; do not edit.",
  " *",
  " * Icons from game-icons.net by Lorc, Delapouite and other contributors, licensed under",
  " * Creative Commons Attribution 3.0 (https://creativecommons.org/licenses/by/3.0/).",
  " * Each value is the `d` of a single path in a 512×512 view box.",
  " */",
  "(function (global) {",
  '  "use strict";',
  "  var SS = (global.SS = global.SS || {});",
  "  SS.ICON_DATA = {",
  Object.keys(out).sort().map((name) => "    " + JSON.stringify(name) + ": " + JSON.stringify(out[name])).join(",\n"),
  "  };",
  '})(typeof window !== "undefined" ? window : globalThis);',
  "",
];
const target = path.join(root, "js", "ui", "icon-data.js");
fs.writeFileSync(target, lines.join("\n"));
console.log("Wrote " + path.relative(root, target) + ": " + Object.keys(out).length + " icons, " +
  Math.round(fs.statSync(target).size / 1024) + " KB");
