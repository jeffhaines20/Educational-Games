#!/usr/bin/env python3
"""Prepare painted artwork for Pyromancer.

Put images in assets/art/source/ named after their slot (any size, PNG/JPG/WebP):

    portrait-ada.png  portrait-pip.png  portrait-glitch.png  portrait-hydra.png
    location-tower.png  location-hall.png  location-circle.png  location-library.png
    location-workshop.png  location-labyrinth.png  location-hydra.png
    map.png  ending.png                                   (optional extras)

then run

    python3 tools/art.py            # crop, resize and compress into assets/art/*.webp
    python3 tools/art.py --check    # just list which slots are filled

Each image is cropped to its slot's shape around a focus point (the centre, or a
bit above it for portraits). To move the crop, add assets/art/source/focus.json:

    { "portrait-ada": [0.5, 0.35, 1.4], "location-hall": [0.4, 0.5] }

(x and y as fractions of the width and height; an optional third number zooms in,
so 1.4 keeps the middle 1/1.4 of the largest crop). The tool rewrites
js/ui/art-manifest.js, which tells the game which paintings exist; any slot
without a painting keeps its icon. Needs Pillow:  pip install pillow
See docs/ART-PROMPTS.md for what each picture should show.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)

# slot -> (width, height, WebP quality, default focus)
PORTRAIT = (640, 640, 82, (0.5, 0.42))
LOCATION = (1200, 800, 78, (0.5, 0.5))
SLOTS = {}
for name in ("ada", "pip", "glitch", "hydra"):
    SLOTS["portrait-" + name] = PORTRAIT
for name in ("tower", "hall", "circle", "library", "workshop", "labyrinth", "hydra"):
    SLOTS["location-" + name] = LOCATION
SLOTS["map"] = (1600, 900, 78, (0.5, 0.5))
SLOTS["ending"] = (1200, 800, 78, (0.5, 0.5))

EXTENSIONS = (".png", ".jpg", ".jpeg", ".webp")

MANIFEST_HEAD = """/*
 * Pyromancer — painted artwork available to the game (SS.ART).
 * GENERATED by tools/art.py from assets/art/source/; do not edit by hand.
 * An empty list means every slot shows its icon. See docs/ART-PROMPTS.md.
 */
(function (global) {
  "use strict";
  var SS = (global.SS = global.SS || {});
"""
MANIFEST_TAIL = """})(typeof window !== "undefined" ? window : globalThis);
"""


def find_sources(source_dir):
    found, unknown = {}, []
    if not os.path.isdir(source_dir):
        return found, unknown
    for entry in sorted(os.listdir(source_dir)):
        stem, ext = os.path.splitext(entry)
        if ext.lower() not in EXTENSIONS:
            continue
        slot = stem.lower()
        if slot in SLOTS:
            found[slot] = os.path.join(source_dir, entry)
        else:
            unknown.append(entry)
    return found, unknown


def crop_box(width, height, target_w, target_h, focus, zoom=1.0):
    """The largest box with the target aspect ratio (shrunk by zoom), centred on focus, kept inside the image."""
    target_ratio = target_w / target_h
    if width / height > target_ratio:
        box_h = height
        box_w = round(height * target_ratio)
    else:
        box_w = width
        box_h = round(width / target_ratio)
    zoom = max(1.0, float(zoom))
    box_w, box_h = round(box_w / zoom), round(box_h / zoom)
    cx, cy = focus[0] * width, focus[1] * height
    left = min(max(0, round(cx - box_w / 2)), width - box_w)
    top = min(max(0, round(cy - box_h / 2)), height - box_h)
    return left, top, left + box_w, top + box_h


def process(slot, path, out_dir, focus_overrides):
    from PIL import Image  # imported here so --check works without Pillow

    target_w, target_h, quality, focus = SLOTS[slot]
    focus = tuple(focus_overrides.get(slot, focus))
    zoom = focus[2] if len(focus) > 2 else 1.0
    with Image.open(path) as image:
        image = image.convert("RGB")
        box = crop_box(image.width, image.height, target_w, target_h, focus[:2], zoom)
        cropped = image.crop(box)
        note = ""
        if cropped.width < target_w:
            if cropped.width >= 0.75 * target_w:
                note = " (kept at %dx%d: a little under the ideal %dx%d, which is fine)" % (cropped.width, cropped.height, target_w, target_h)
            else:
                note = " (source is small: kept at %dx%d and may look soft; ideally %dx%d or larger)" % (cropped.width, cropped.height, target_w, target_h)
            target_w, target_h = cropped.width, cropped.height
        final = cropped.resize((target_w, target_h), Image.LANCZOS)
        out_path = os.path.join(out_dir, slot + ".webp")
        final.save(out_path, "WEBP", quality=quality, method=6)
    return out_path, final.size, note


def write_manifest(manifest_path, entries):
    lines = [MANIFEST_HEAD, "  SS.ART = {\n"]
    items = []
    for slot in sorted(entries):
        src, (w, h) = entries[slot]
        items.append('    %s: { src: %s, width: %d, height: %d }' % (json.dumps(slot), json.dumps(src), w, h))
    lines.append(",\n".join(items) + ("\n" if items else ""))
    lines.append("  };\n")
    lines.append(MANIFEST_TAIL)
    with open(manifest_path, "w", encoding="utf-8") as fh:
        fh.write("".join(lines))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", default=os.path.join(GAME, "assets", "art", "source"))
    parser.add_argument("--out", default=os.path.join(GAME, "assets", "art"))
    parser.add_argument("--manifest", default=os.path.join(GAME, "js", "ui", "art-manifest.js"))
    parser.add_argument("--url-prefix", default="assets/art/", help="how the game refers to the output folder")
    parser.add_argument("--check", action="store_true", help="only report which slots have a source image")
    args = parser.parse_args(argv)

    found, unknown = find_sources(args.source)
    for name in unknown:
        print("warning: " + name + " doesn't match a slot name; expected one of: " + ", ".join(sorted(SLOTS)))
    if args.check:
        for slot in sorted(SLOTS):
            print(("✓ " if slot in found else "· ") + slot + ("  ← " + os.path.basename(found[slot]) if slot in found else ""))
        print("%d of %d slots filled" % (len(found), len(SLOTS)))
        return 0

    try:
        import PIL  # noqa: F401
    except ImportError:
        print("This tool needs Pillow. Install it with:  python3 -m pip install pillow")
        return 2

    focus_overrides = {}
    focus_file = os.path.join(args.source, "focus.json")
    if os.path.exists(focus_file):
        with open(focus_file, encoding="utf-8") as fh:
            focus_overrides = json.load(fh)

    os.makedirs(args.out, exist_ok=True)
    entries = {}
    for slot in sorted(found):
        out_path, size, note = process(slot, found[slot], args.out, focus_overrides)
        entries[slot] = (args.url_prefix + os.path.basename(out_path), size)
        print("%-20s %4dx%-4d %4d KB%s" % (slot, size[0], size[1], os.path.getsize(out_path) // 1024, note))
    # Keep outputs from earlier runs whose source has since been removed from source/.
    for slot in sorted(SLOTS):
        existing = os.path.join(args.out, slot + ".webp")
        if slot not in entries and os.path.exists(existing):
            from PIL import Image
            with Image.open(existing) as image:
                entries[slot] = (args.url_prefix + slot + ".webp", image.size)
    write_manifest(args.manifest, entries)
    print("Wrote %s with %d painting(s); %d slot(s) still use icons." % (
        os.path.relpath(args.manifest, GAME) if args.manifest.startswith(GAME) else args.manifest,
        len(entries), len(SLOTS) - len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
