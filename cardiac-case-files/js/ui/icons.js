/*
 * The Cardiac Case Files — icons (CCF.Icons).
 *
 * Every picture in the interface is an icon from game-icons.net (by Lorc, Delapouite and
 * other contributors, CC BY 3.0), drawn as an inline <svg> and tinted with CSS `color`, so
 * it looks the same on every computer — unlike emoji.
 *
 *   CCF.Icons.svg("stethoscope", { label: "Exam", className: "x" })  → <svg> (or null)
 *   CCF.Icons.UI.hint        → the icon name for a piece of interface
 *   CCF.Icons.unit("rhythm") → the icon name for a unit (falls back to the unit's own icon)
 *   CCF.Icons.nameFor(name)  → name if the icon exists, else null
 *
 * The path data lives in js/ui/icon-data.js, generated by `node tools/build_icons.js` from
 * every name used in this file (plus the units' icons in js/content/registry.js). Add a
 * name here, re-run the tool, and the icon is available.
 */
(function (global) {
  "use strict";
  var CCF = (global.CCF = global.CCF || {});
  var NS = "http://www.w3.org/2000/svg";

  /** Interface pieces → icon. */
  var UI = {
    brand: "heart-beats", detective: "sherlock-holmes", mentor: "stethoscope", narrator: "notebook",
    board: "full-folder", folder: "open-folder", files: "files", casebook: "archive-research",
    rounds: "stopwatch", log: "checklist", certificate: "diploma", settings: "cog",
    soundOn: "speaker", soundOff: "speaker-off", menu: "hamburger-menu", info: "info",
    lock: "padlock", unlock: "padlock-open", stamp: "stamper", clip: "paper-clip",
    hint: "light-bulb", tip: "light-bulb", warn: "siren", warning: "hazard-sign",
    correct: "check-mark", wrong: "cross-mark", update: "pocket-watch", progress: "hourglass",
    referral: "envelope", history: "notebook", medications: "medicines", vitals: "heart-beats",
    exam: "stethoscope", tests: "test-tubes", patient: "person", setting: "hospital-cross",
    ecg: "heart-beats", labs: "test-tubes", table: "checklist", report: "papers", note: "quill-ink",
    diagram: "stethoscope", sealed: "wax-seal", search: "magnifying-glass", rank: "police-badge",
    xp: "star-medal", trophy: "laurels-trophy", print: "papers", exportSave: "share",
    importSave: "save-arrow", remove: "trash-can", replay: "anticlockwise-rotation",
    next: "plain-arrow", back: "return-arrow", textSize: "papers", motion: "hourglass",
    emergency: "ambulance", pill: "pill", describe: "notebook", lamp: "desk-lamp", newGame: "open-folder",
    easy: "rank-1", medium: "rank-2", hard: "rank-3", edema: "barefoot", abi: "leg",
    pressure: "speedometer", rhythm: "heart-beats", coffee: "coffee-cup"
  };

  /** Unit id → icon (chosen by hand; registry.js also gives each unit an icon). */
  var UNITS = {
    basics: "stethoscope", coronary: "heart-organ", rhythm: "heart-beats",
    pump: "lungs", pressure: "speedometer", vessels: "leg"
  };

  /** Character id → icon. */
  var CHARACTERS = { okafor: "stethoscope", narrator: "notebook", player: "sherlock-holmes" };

  /** Exhibit type → icon. */
  var EXHIBITS = { ecg: "heart-beats", labs: "test-tubes", table: "checklist", report: "papers", note: "quill-ink", diagram: "stethoscope" };

  /** Drill id → icon. */
  var DRILLS = { rhythm: "heart-beats", pressure: "speedometer", abi: "leg", edema: "barefoot" };

  /** Icons content may name (registry units) — kept here so the build includes them. */
  var EXTRA = ["heart-organ", "heart-beats", "pulse", "lungs", "leg", "speedometer", "medical-thermometer",
    "brain", "kidneys", "drop", "blood", "weight-scale", "syringe", "pill", "walk", "person-in-bed",
    "cigarette", "snowflake-1", "magnifying-glass", "trophy"];

  function data() { return CCF.ICON_DATA || {}; }

  function has(name) {
    return typeof name === "string" && Object.prototype.hasOwnProperty.call(data(), name);
  }

  /** An inline <svg> for an icon name, or null if the icon isn't available. */
  function svg(name, opts) {
    opts = opts || {};
    if (!has(name) || typeof document === "undefined") return null;
    var el = document.createElementNS(NS, "svg");
    el.setAttribute("viewBox", "0 0 512 512");
    el.setAttribute("class", "gi gi-" + name + (opts.className ? " " + opts.className : ""));
    el.setAttribute("focusable", "false");
    if (opts.label) {
      el.setAttribute("role", "img");
      el.setAttribute("aria-label", String(opts.label));
    } else {
      el.setAttribute("aria-hidden", "true");
    }
    var path = document.createElementNS(NS, "path");
    path.setAttribute("d", data()[name]);
    path.setAttribute("fill", "currentColor");
    el.appendChild(path);
    return el;
  }

  /** The icon name for a UI key or a bare icon name, or null. */
  function nameFor(value) {
    if (value === null || value === undefined) return null;
    var key = String(value).trim();
    if (Object.prototype.hasOwnProperty.call(UI, key)) key = UI[key];
    if (key.indexOf("icon:") === 0) key = key.slice(5);
    return has(key) ? key : null;
  }

  function unit(id, fallback) {
    var name = UNITS[id];
    if (name && has(name)) return name;
    if (fallback && has(fallback)) return fallback;
    return has("open-folder") ? "open-folder" : null;
  }

  /** Every icon name this file refers to (used by tools/build_icons.js). */
  function allNames() {
    var names = {};
    [UI, UNITS, CHARACTERS, EXHIBITS, DRILLS].forEach(function (table) {
      Object.keys(table).forEach(function (key) { names[table[key]] = true; });
    });
    EXTRA.forEach(function (n) { names[n] = true; });
    return Object.keys(names).sort();
  }

  CCF.Icons = {
    svg: svg,
    has: has,
    nameFor: nameFor,
    unit: unit,
    character: function (id) { return CHARACTERS[id] || CHARACTERS.narrator; },
    exhibit: function (type) { return EXHIBITS[type] || "papers"; },
    drill: function (id) { return DRILLS[id] || "stopwatch"; },
    allNames: allNames,
    UI: UI,
    UNITS: UNITS,
    credit: "Icons by the game-icons.net contributors (Lorc, Delapouite and others), CC BY 3.0 — https://game-icons.net"
  };
})(typeof window !== "undefined" ? window : globalThis);
